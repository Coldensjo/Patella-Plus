"""Build the Linux client's built-in cursor resources and window icon (Patella-Modern issues #131, #162).

Usage: python3 -I tools/embed_cursors.py <resource folder> <output.cpp>

Reads cursor_<id>.cur and icon_128.ico in the folder written by tools/extract_resources.py (or
tools/placeholder_resources.py) and writes a C++ source with the first image of each cursor in the form of an RT_CURSOR
resource (the two hot spot words, then the DIB: platform::DecodeMonochromeCursor's input, src/platform/CursorImage.h) and
platform::EmbeddedCursor(id), and the icon's largest image as an RT_ICON resource (its DIB, unchanged:
platform::DecodeIconImage's input, src/platform/WindowIcon.h) and platform::EmbeddedIcon(). Only the largest: SDL's X11
driver writes one image, and its Wayland driver ignores those smaller than the first. The source is generated into the
build folder: the bytes of a local Tibia.exe never reach the repository.
"""

import glob
import os
import re
import struct
import sys

CUR, ICO = 2, 1


def images(path, expected=CUR):
	"""The images of a .cur or .ico file, [(hot x or planes, hot y or bits, width, height, DIB bytes)], in file order."""
	with open(path, "rb") as f:
		data = f.read()
	reserved, kind, count = struct.unpack_from("<HHH", data, 0)
	if reserved != 0 or kind != expected:
		raise ValueError("%s: not a %s file" % (path, "cursor" if expected == CUR else "icon"))
	found = []
	for index in range(count):
		width, height, colors, reserved, hot_x, hot_y, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + index * 16)
		dib = data[offset:offset + size]
		if len(dib) != size:
			raise ValueError("%s: image %d is cut short" % (path, index))
		found.append((hot_x, hot_y, width or 256, height or 256, dib))
	return found


def main():
	if len(sys.argv) != 3:
		sys.exit("usage: embed_cursors.py <resource folder> <output.cpp>")
	folder, output = sys.argv[1:]
	entries = []
	for path in sorted(glob.glob(os.path.join(folder, "cursor_*.cur"))):
		match = re.fullmatch(r"cursor_(\d+)\.cur", os.path.basename(path))
		if match is None:
			continue
		found = images(path)
		if not found:
			continue
		# LoadCursor picks the system's cursor size (32 x 32); the first image of a size is taken, else the first image.
		chosen = next((image for image in found if image[2] == 32 and image[3] == 32), found[0])
		hot_x, hot_y, _, _, dib = chosen
		entries.append((int(match.group(1)), struct.pack("<HH", hot_x, hot_y) + dib))
	# The largest image, and of those the deepest (the DIB's own bit count: a group entry's may be 0).
	icon = max(images(os.path.join(folder, "icon_128.ico"), ICO), key=lambda image: (image[2] * image[3], image[4][14]))[4]
	lines = ["// Generated by tools/embed_cursors.py (issues #131, #162): the cursor resources and the window icon, built in. Not in "
		"the repository.", '#include "platform/CursorImage.h"', '#include "platform/WindowIcon.h"', "", "#include <array>",
		"#include <cstdint>", "#include <span>", "", "namespace patella::platform {", "", "namespace {", ""]
	for number, blob in entries:
		bytes_text = ",".join(str(value) for value in blob)
		lines.append("constexpr std::array<std::uint8_t, %d> Cursor%d = {%s};" % (len(blob), number, bytes_text))
	lines.append("constexpr std::array<std::uint8_t, %d> Icon = {%s};" % (len(icon), ",".join(str(value) for value in icon)))
	lines += ["", "} // namespace", "", "std::span<const std::uint8_t> EmbeddedCursor(int Id)", "{", "\tswitch (Id) {"]
	for number, _ in entries:
		lines.append("\tcase %d: return Cursor%d;" % (number, number))
	lines += ["\tdefault: return {};", "\t}", "}", "", "std::span<const std::uint8_t> EmbeddedIcon()", "{", "\treturn Icon;", "}",
		"", "} // namespace patella::platform", ""]
	with open(output, "w", encoding="ascii", newline="\n") as f:
		f.write("\n".join(lines))


if __name__ == "__main__":
	main()
